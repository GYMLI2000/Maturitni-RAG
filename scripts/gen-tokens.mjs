// Generates app/tokens.css from the `variables` of design/MaturitaRAG.pen.
// Run: node scripts/gen-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const pen = JSON.parse(readFileSync(new URL("../design/MaturitaRAG.pen", import.meta.url), "utf8"));
const light = [];
const dark = [];

for (const [name, def] of Object.entries(pen.variables)) {
  if (def.type !== "color") continue;
  const byMode = Object.fromEntries(def.value.map((v) => [v.theme.mode, v.value]));
  if (!byMode.light || !byMode.dark) throw new Error(`Token ${name} is missing a light or dark value`);
  light.push(`  --${name}: ${byMode.light};`);
  dark.push(`  --${name}: ${byMode.dark};`);
}

const css = `/* Generated by scripts/gen-tokens.mjs from design/MaturitaRAG.pen. Do not edit by hand. */
:root {
${light.join("\n")}
}

.dark {
${dark.join("\n")}
}
`;

writeFileSync(new URL("../app/tokens.css", import.meta.url), css);
console.log(`Wrote ${light.length} tokens to app/tokens.css`);
